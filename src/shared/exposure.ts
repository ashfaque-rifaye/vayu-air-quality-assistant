/**
 * Exposure arithmetic: the deterministic heart of "clearly explaining the direct
 * impact of your choices". Never the model's job.
 *
 * It estimates the PM2.5 a household actually breathes in a day as an inhaled
 * dose (concentration x time x how hard they are breathing), split across the
 * parts of a day, and works out exactly how much each mitigation removes. The
 * model never touches these numbers; it only explains and tailors them.
 *
 * Dose is in ug/m3-hours, weighted by breathing rate. It is a transparent model,
 * not a medical measurement, and the UI words it that way.
 */
import { averageOverHours, indoorPm25, purifierReduction, WHO_DAILY_PM25 } from "./aqi.js";
import type {
  ActivityLevel,
  AirQuality,
  CommuteMode,
  CookingFuel,
  HeatingType,
  Home,
  MeasureCategory,
  Plan,
  Profile,
  Ventilation,
} from "./schemas.js";

/** Breathing-rate multipliers relative to sitting at rest (minute ventilation). */
export const BREATHING = { rest: 0.8, light: 1.0, moderate: 2.0, intense: 5.0 } as const;

/** A clean day at the WHO guideline, breathed at an average rate: the safe target. */
export const TARGET_DOSE = WHO_DAILY_PM25 * 24;

/**
 * Berkeley Earth's rule of thumb: a day at 22 ug/m3 PM2.5 is about one cigarette.
 * Used only to make an abstract dose tangible, never as a medical claim.
 */
export const DOSE_PER_CIGARETTE = 22 * 24;

/** Reduction assumed for a correctly sized purifier when its CADR is unknown. */
const DEFAULT_PURIFIER_REDUCTION = 0.6;

/** Indoor PM2.5 generated by occupants, cooking aside; timed ventilation halves it. */
const INDOOR_BASELINE = 5;
const VENTILATED_INDOOR_BASELINE = 2.5;

const COOKING_SOURCE: Record<CookingFuel, number> = {
  induction: 0,
  lpg: 10,
  gas: 15,
  wood: 120,
  kerosene: 90,
};

const HEATING_SOURCE: Record<HeatingType, number> = { none: 0, electric: 0, gas: 10, wood: 70 };

interface CommuteProfile {
  breathing: number;
  /** Fraction of ambient PM2.5 experienced inside this mode of transport. */
  enclosure: number;
}

const COMMUTE_PROFILE: Record<CommuteMode, CommuteProfile> = {
  none: { breathing: BREATHING.light, enclosure: 0 },
  walk: { breathing: BREATHING.moderate, enclosure: 1 },
  cycle: { breathing: BREATHING.intense, enclosure: 1 },
  metro: { breathing: BREATHING.light, enclosure: 0.5 },
  bus: { breathing: BREATHING.light, enclosure: 0.9 },
  car: { breathing: BREATHING.light, enclosure: 0.7 },
  motorbike: { breathing: BREATHING.moderate, enclosure: 1.15 },
};

interface ActivityProfile {
  hours: number;
  breathing: number;
}

const ACTIVITY_PROFILE: Record<ActivityLevel, ActivityProfile> = {
  none: { hours: 0, breathing: BREATHING.light },
  light: { hours: 0.5, breathing: BREATHING.light },
  moderate: { hours: 0.75, breathing: BREATHING.moderate },
  intense: { hours: 1, breathing: BREATHING.intense },
};

export interface ExposureSegment {
  id: "sleep" | "cooking" | "commute" | "outdoor" | "home";
  label: string;
  place: "indoor" | "outdoor";
  hours: number;
  /** Ambient outdoor PM2.5 during this segment's hours. */
  outdoorPm25: number;
  /** PM2.5 actually breathed after walls, filters, masks and sources. */
  effectivePm25: number;
  breathing: number;
  /** effectivePm25 x hours x breathing. */
  dose: number;
}

export interface ExposureSummary {
  segments: ExposureSegment[];
  /** Dose with the measures the household has actually adopted. */
  totalDose: number;
  /** Dose doing nothing new. */
  baselineDose: number;
  /** Dose with every modelled measure adopted. */
  protectedDose: number;
  targetDose: number;
  over: boolean;
  /** How far over the safe target, as a whole-number multiple (>= 1). */
  timesTarget: number;
  reductionAchieved: number;
  reductionPossible: number;
  cigarettesEquivalent: number;
  cigarettesAvoidable: number;
}

function hourOf(time: string): number {
  return Math.max(0, Math.min(23, Number.parseInt(time.slice(0, 2), 10) || 0));
}

function tighten(ventilation: Ventilation): Ventilation {
  if (ventilation === "leaky") return "average";
  if (ventilation === "average") return "sealed";
  return "sealed";
}

type Adopted = ReadonlySet<MeasureCategory>;

function round(dose: number): number {
  return Math.round(dose);
}

type SegmentProfile = Pick<
  Profile,
  "commuteMode" | "commuteMinutes" | "commuteTime" | "outdoorActivity" | "outdoorTime"
>;

const COOKING_HOURS = 2;
const SLEEP_HOURS = 8;
const WAKING_HOURS = 16;

/** How the home and the adopted measures shape the air the household breathes. */
interface Environment {
  hourly: readonly number[];
  /** Outdoor air near a busy road carries more particles. */
  roadFactor: number;
  /** A fitted N95 removes about 90% of what reaches the face. */
  maskFactor: number;
  cookingFuel: CookingFuel;
  heatingSource: number;
  /** Indoor PM2.5 for a given outdoor level, extra indoor source and purifier use. */
  indoor: (outdoor: number, extraSource: number, purifierHere?: boolean) => number;
}

function purifierEffect(home: Home, adopted: Adopted): number {
  if (!adopted.has("purifier")) return 0;
  return home.purifierCadr && home.purifierCadr > 0
    ? purifierReduction(home.purifierCadr, home.roomSqm)
    : DEFAULT_PURIFIER_REDUCTION;
}

function environment(home: Home, air: AirQuality, adopted: Adopted): Environment {
  const ventilation = adopted.has("sealing") ? tighten(home.ventilation) : home.ventilation;
  const indoorBaseline = adopted.has("ventilation") ? VENTILATED_INDOOR_BASELINE : INDOOR_BASELINE;
  const plantsBonus = adopted.has("plants") ? 1 : 0;
  const reduction = purifierEffect(home, adopted);
  return {
    hourly: air.hourly,
    roadFactor: home.nearRoad ? 1.2 : 1,
    maskFactor: adopted.has("masks") ? 0.1 : 1,
    cookingFuel: adopted.has("cooking") ? "induction" : home.cookingFuel,
    heatingSource: adopted.has("heating") ? 0 : HEATING_SOURCE[home.heating],
    indoor: (outdoor, extraSource, purifierHere = true) =>
      indoorPm25(outdoor, {
        ventilation,
        purifierReduction: purifierHere ? reduction : 0,
        indoorSource: Math.max(0, indoorBaseline - plantsBonus + extraSource),
      }),
  };
}

/** Average outdoor PM2.5 over a stretch of whole hours starting at a clock time. */
function outdoorOver(env: Environment, time: string | number, hours: number): number {
  const start = typeof time === "number" ? time : hourOf(time);
  return averageOverHours(env.hourly, start, Math.max(1, Math.round(hours)));
}

function commuteHoursOf(profile: SegmentProfile): number {
  return profile.commuteMode === "none" ? 0 : Math.min(8, (profile.commuteMinutes * 2) / 60);
}

function sleepSegment(env: Environment): ExposureSegment {
  const outdoor = outdoorOver(env, 23, SLEEP_HOURS);
  return segment({
    id: "sleep",
    label: "Sleep",
    place: "indoor",
    hours: SLEEP_HOURS,
    outdoorPm25: outdoor,
    effectivePm25: env.indoor(outdoor, env.heatingSource),
    breathing: BREATHING.rest,
  });
}

/** Two indoor hours carrying the stove's own particles, with the purifier usually off. */
function cookingSegment(env: Environment): ExposureSegment {
  const outdoor = outdoorOver(env, 19, COOKING_HOURS);
  const source = env.heatingSource + COOKING_SOURCE[env.cookingFuel];
  return segment({
    id: "cooking",
    label: "Cooking",
    place: "indoor",
    hours: COOKING_HOURS,
    outdoorPm25: outdoor,
    effectivePm25: env.indoor(outdoor, source, false),
    breathing: BREATHING.light,
  });
}

/** Ambient air, lightly filtered by the vehicle, or not at all on foot or two wheels. */
function commuteSegment(env: Environment, profile: SegmentProfile, adopted: Adopted) {
  const hours = commuteHoursOf(profile);
  if (hours <= 0) return null;
  const mode = COMMUTE_PROFILE[profile.commuteMode];
  const outdoor = outdoorOver(env, profile.commuteTime, hours);
  const cleaner = adopted.has("commute") ? 0.55 : 1;
  return segment({
    id: "commute",
    label: "Commute",
    place: "outdoor",
    hours,
    outdoorPm25: outdoor,
    effectivePm25: outdoor * mode.enclosure * env.roadFactor * env.maskFactor * cleaner,
    breathing: mode.breathing,
  });
}

/** The biggest dose on a smoggy day, through hard breathing, unless moved indoors. */
function activitySegment(env: Environment, profile: SegmentProfile, adopted: Adopted) {
  const activity = ACTIVITY_PROFILE[profile.outdoorActivity];
  if (activity.hours <= 0) return null;
  const outdoor = outdoorOver(env, profile.outdoorTime, activity.hours);
  const movedIndoors = adopted.has("exercise");
  return segment({
    id: "outdoor",
    label: movedIndoors ? "Exercise (indoors)" : "Outdoor activity",
    place: movedIndoors ? "indoor" : "outdoor",
    hours: activity.hours,
    outdoorPm25: outdoor,
    effectivePm25: movedIndoors
      ? env.indoor(outdoor, 0)
      : outdoor * env.roadFactor * env.maskFactor,
    breathing: activity.breathing,
  });
}

/** Everything else awake, at home. */
function homeSegment(env: Environment, profile: SegmentProfile) {
  const outdoorHours = ACTIVITY_PROFILE[profile.outdoorActivity].hours;
  const hours = WAKING_HOURS - commuteHoursOf(profile) - outdoorHours - COOKING_HOURS;
  if (hours <= 0) return null;
  const outdoor = outdoorOver(env, 8, 12);
  return segment({
    id: "home",
    label: "At home (awake)",
    place: "indoor",
    hours: round1(hours),
    outdoorPm25: outdoor,
    effectivePm25: env.indoor(outdoor, env.heatingSource),
    breathing: BREATHING.light,
  });
}

/** Build the day's exposure segments for a given set of adopted measures. */
export function computeSegments(
  profile: SegmentProfile,
  home: Home,
  air: AirQuality,
  adopted: Adopted,
): ExposureSegment[] {
  const env = environment(home, air, adopted);
  return [
    sleepSegment(env),
    cookingSegment(env),
    commuteSegment(env, profile, adopted),
    activitySegment(env, profile, adopted),
    homeSegment(env, profile),
  ].filter((segment): segment is ExposureSegment => segment !== null);
}

function segment(
  parts: Omit<ExposureSegment, "dose" | "effectivePm25"> & { effectivePm25: number },
): ExposureSegment {
  const effective = Math.max(0, parts.effectivePm25);
  return {
    ...parts,
    hours: round1(parts.hours),
    outdoorPm25: round1(parts.outdoorPm25),
    effectivePm25: round1(effective),
    dose: round(effective * parts.hours * parts.breathing),
  };
}

function round1(value: number): number {
  return Math.round(value * 10) / 10;
}

function totalDose(segments: readonly ExposureSegment[]): number {
  return segments.reduce((sum, s) => sum + s.dose, 0);
}

/** Every measure the exposure model actually responds to. */
export const MODELLED_MEASURES: readonly MeasureCategory[] = [
  "purifier",
  "masks",
  "sealing",
  "ventilation",
  "cooking",
  "commute",
  "exercise",
  "heating",
  "plants",
];

export interface ExposureInput {
  profile: Profile;
  home: Home;
  air: AirQuality;
  /** Measure categories the household has marked done. */
  adopted: Adopted;
}

export function exposureSummary(input: ExposureInput): ExposureSummary {
  const { profile, home, air, adopted } = input;
  const current = computeSegments(profile, home, air, adopted);
  const baseline = totalDose(computeSegments(profile, home, air, new Set()));
  const protectedDose = totalDose(computeSegments(profile, home, air, new Set(MODELLED_MEASURES)));
  const total = totalDose(current);

  return {
    segments: current,
    totalDose: total,
    baselineDose: baseline,
    protectedDose,
    targetDose: TARGET_DOSE,
    over: total > TARGET_DOSE,
    timesTarget: Math.max(1, Math.round(total / TARGET_DOSE)),
    reductionAchieved: Math.max(0, baseline - total),
    reductionPossible: Math.max(0, baseline - protectedDose),
    cigarettesEquivalent: Math.round((total / DOSE_PER_CIGARETTE) * 10) / 10,
    cigarettesAvoidable: Math.round(((baseline - protectedDose) / DOSE_PER_CIGARETTE) * 10) / 10,
  };
}

/**
 * The dose a single measure removes, measured from the do-nothing baseline. This
 * is the number shown against each action, the literal "direct impact".
 */
export function measureImpact(
  category: MeasureCategory,
  input: Omit<ExposureInput, "adopted">,
): number {
  if (category === "monitoring") return 0;
  const baseline = totalDose(computeSegments(input.profile, input.home, input.air, new Set()));
  const withOne = totalDose(
    computeSegments(input.profile, input.home, input.air, new Set([category])),
  );
  return Math.max(0, Math.round(baseline - withOne));
}

/** Measure categories the household has marked done. */
export function adoptedCategories(plan: Pick<Plan, "measures">): Set<MeasureCategory> {
  return new Set(plan.measures.filter((m) => m.status === "done").map((m) => m.category));
}

/** A dose rendered for people: a rounded number with its unit. */
export function formatDose(dose: number): string {
  return `${Math.round(dose).toLocaleString("en-US")} µg/m³·h`;
}

/** A dose expressed as cigarettes, the tangible framing used across the UI. */
export function cigarettes(dose: number): number {
  return Math.round((dose / DOSE_PER_CIGARETTE) * 10) / 10;
}

/** The exposure summary for a whole plan, the view both the UI and context use. */
export function planExposure(plan: Pick<Plan, "profile" | "air" | "measures">): ExposureSummary {
  return exposureSummary({
    profile: plan.profile,
    home: plan.profile.home,
    air: plan.air,
    adopted: adoptedCategories(plan),
  });
}
